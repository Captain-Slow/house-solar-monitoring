export type Dtype = 'U16' | 'I16' | 'U32' | 'I32' | 'H32' | 'I32R';
export type FunctionCode = 3 | 4;
export type BoundsEvidence = 'library-validation' | 'datasheet+design-margin';

export interface RegisterDef {
  readonly key: string;
  readonly addr: number;
  /** 4 = input registers (FC04), 3 = holding registers (FC03). */
  readonly fc: FunctionCode;
  readonly dtype: Dtype;
  readonly scale: number;
  readonly unit: string | null;
  readonly enum?: Readonly<Record<number, string>>;
  readonly bitmap?: Readonly<Record<number, string>>;
  readonly bounds?: readonly [number, number];
  readonly boundsEvidence?: BoundsEvidence;
  /** A raw value of 0 is exempt from `bounds` (frequency is 0 when the grid is off). */
  readonly boundsAllowZero?: boolean;
}

